// Package docsgen writes docs/configuration.md: the environment variables
// (config.Vars) and the settings (their definitions), so the reference
// follows the code; and ui/src/lib/settings.generated.json, the settings
// the UI's layout test checks are each placed. `go run ./cmd/gendocs`
// regenerates both; tests check they are current.
package docsgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/damhau/awxnext/internal/config"
	// Registers the settings defined with the API (named URLs).
	_ "github.com/damhau/awxnext/internal/resources"
	"github.com/damhau/awxnext/internal/settings"
)

// Configuration is docs/configuration.md.
func Configuration() string {
	var b strings.Builder
	b.WriteString("# Configuration reference\n\n")
	b.WriteString("<!-- Generated by `go run ./cmd/gendocs` from internal/config/vars.go and the settings definitions; do not edit. -->\n\n")
	b.WriteString("awxnext is configured by environment variables, read when a process starts, and by settings,\n")
	b.WriteString("kept in the database and changed through `/api/v2/settings/<category>/` (or the Settings pages)\n")
	b.WriteString("by a system administrator, as in AWX.\n\n")
	b.WriteString("## Environment variables\n")
	group := ""
	for _, v := range config.Vars {
		if v.Group != group {
			group = v.Group
			fmt.Fprintf(&b, "\n### %s\n\n| Variable | Default | |\n|---|---|---|\n", group)
		}
		// A value in code font, a description ("the host name") not.
		def := v.Default
		if def != "" && !strings.Contains(def, " ") {
			def = "`" + def + "`"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", v.Name, def, cell(v.Help))
	}
	b.WriteString("\n## Settings\n\nBy category, with the type and default. Settings marked *no effect* are accepted so AWX\n")
	b.WriteString("clients and imports keep working.\n")
	for _, c := range settings.Categories {
		if c.Slug == "changed" || c.Slug == "named-url" {
			continue
		}
		defs := settings.InCategory(c.Slug)
		if len(defs) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n### %s (`/api/v2/settings/%s/`)\n\n| Setting | Type | Default | |\n|---|---|---|---|\n", c.Name, c.Slug)
		for _, d := range defs {
			help := d.Help
			if d.CompatOnly {
				help = "*No effect.* " + strings.TrimPrefix(strings.TrimPrefix(help, "No effect in awxnext: "), "No effect in awxnext")
			}
			var flags []string
			if d.Secret {
				flags = append(flags, "secret")
			}
			if d.ReadOnly {
				flags = append(flags, "read-only")
			}
			if d.Public {
				flags = append(flags, "readable by every user")
			}
			if len(flags) > 0 {
				help += " (" + strings.Join(flags, ", ") + ")"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", d.Key, d.Type, value(d.Default), cell(help))
		}
	}
	return b.String()
}

// SettingsList is ui/src/lib/settings.generated.json: each setting the API
// has, by key, with its AWX category, and whether it has no effect in
// awxnext. The settings layout's test reads it.
func SettingsList() string {
	var b strings.Builder
	b.WriteString("{\n  \"_\": \"Generated by go run ./cmd/gendocs from the settings definitions; do not edit.\",\n  \"settings\": {")
	var keys []string
	cat := map[string]*settings.Def{}
	for _, c := range settings.Categories {
		if c.Slug == "all" || c.Slug == "changed" {
			continue
		}
		for _, d := range settings.InCategory(c.Slug) {
			keys = append(keys, d.Key)
			cat[d.Key] = d
		}
	}
	sort.Strings(keys)
	for i, k := range keys {
		d := cat[k]
		if i > 0 {
			b.WriteString(",")
		}
		fmt.Fprintf(&b, "\n    %q: {\"category\": %q", k, d.Category)
		if d.CompatOnly {
			b.WriteString(", \"no_effect\": true")
		}
		b.WriteString("}")
	}
	b.WriteString("\n  }\n}\n")
	return b.String()
}

func value(v any) string {
	if v == nil {
		return "null"
	}
	var j bytes.Buffer
	e := json.NewEncoder(&j)
	e.SetEscapeHTML(false)
	e.Encode(v)
	s := strings.TrimSpace(j.String())
	if len(s) > 60 {
		s = s[:57] + "..."
	}
	return "`" + strings.ReplaceAll(s, "|", "\\|") + "`"
}

func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ")
}
